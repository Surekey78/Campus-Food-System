/**
 * Work out the URL path the app is served from.
 *   php -S host:port -t public   ->  ''            (served at "/")
 *   XAMPP htdocs/campus-food/public -> '/campus-food/public'
 */
if (!defined('BASE_URL')) {
    $docRoot = isset($_SERVER['DOCUMENT_ROOT'])
        ? rtrim(str_replace('\\', '/', realpath($_SERVER['DOCUMENT_ROOT']) ?: ''), '/')
        : '';
    $pub     = rtrim(str_replace('\\', '/', realpath(PUBLIC_ROOT) ?: PUBLIC_ROOT), '/');

    define('BASE_URL', ($docRoot !== '' && str_starts_with($pub, $docRoot)) ? substr($pub, strlen($docRoot)) : '');
}

/** Build an in-app URL: url('/login.php') -> '/campus-food/public/login.php' */
function url(string $path = '/'): string
{
    return BASE_URL . '/' . ltrim($path, '/');
}

// =====================================================================
//  2. mysqli query helpers
//     Every query goes through a prepared statement, so user input can
//     never be interpreted as SQL.
// =====================================================================

/**
 * Prepare, bind and execute a statement.
 * @param  array<int|string,mixed> $params values for the ?'s, in order
 */
function db_run(string $sql, array $params = []): mysqli_stmt
{
    $stmt = db()->prepare($sql);

    if ($stmt === false) {
        throw new RuntimeException('SQL prepare failed: ' . db()->error . ' | ' . $sql);
    }

    if ($params !== []) {
        // Bind everything as a string: MySQL/MariaDB coerces "42" -> 42
        // for numeric columns, and escaping is handled for us.
        $stmt->bind_param(str_repeat('s', count($params)), ...array_values($params));
    }

    $stmt->execute();

    return $stmt;
}

/** Run a SELECT and return every row as an associative array. */
function db_all(string $sql, array $params = []): array
{
    $res  = db_run($sql, $params)->get_result();
    $rows = $res->fetch_all(MYSQLI_ASSOC);
    $res->free();

    return $rows;
}

/** Run a SELECT and return the first row, or null when there is none. */
function db_one(string $sql, array $params = []): ?array
{
    $res = db_run($sql, $params)->get_result();
    $row = $res->fetch_assoc();
    $res->free();

    return $row ?: null;
}

/** Run a SELECT and return a single value (first column of first row). */
function db_val(string $sql, array $params = [], mixed $default = null): mixed
{
    $row = db_one($sql, $params);

    if ($row === null) {
        return $default;
    }

    return array_values($row)[0] ?? $default;
}

/** Run INSERT / UPDATE / DELETE. Returns affected rows. */
function db_exec(string $sql, array $params = []): int
{
    return db_run($sql, $params)->affected_rows;
}

/** id generated by the last INSERT. */
function db_insert_id(): int
{
    return (int) db()->insert_id;
}

/** Most recent SQL error, handy while debugging. */
function db_last_error(): string
{
    return db()->error;
}

