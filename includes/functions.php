/** Escape for safe HTML output. Use on EVERY variable you echo. */
function e(mixed $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/**
 * Count characters.
 * Prefers mbstring (correct for Unicode names), but falls back to strlen
 * so the app still runs on a PHP build without the mbstring extension.
 */
function char_len(string $text): int
{
    return function_exists('mb_strlen') ? mb_strlen($text, 'UTF-8') : strlen($text);
}

/** 1234.5 -> "₱1,234.50" */
function money(float|int|string|null $amount): string
{
    return CURRENCY . number_format((float) $amount, 2);
}

/**
 * Resolve a menu photo to a URL at the size the page actually needs.
 *
 *   'card'  ~512px wide, for the menu grid
 *   'tiny'  ~160px wide, for admin table rows
 *   'full'  the original
 *
 * Thumbnails are made by tools/make-thumbs.py (demo photos) and by the
 * uploader (a canteen's own photos). If one is missing — a fresh clone
 * that hasn't run the tool yet, say — this quietly falls back to the
 * full-size file rather than showing a broken image.
 */
function menu_photo_url(?string $path, string $size = 'card'): ?string
{
    if ($path === null || $path === '') {
        return null;
    }

    if ($size === 'full') {
        return $path;
    }

    $sub = match ($size) {
        'tiny' => 'thumbs/tiny/',
        'card' => 'thumbs/',
        default => null,
    };

    if ($sub === null) {
        return $path;
    }

    // Only rewrite the two shapes we generate. Anything else (a canteen
    // pointing at a photo hosted elsewhere, say) is passed through as-is,
    // so no user-supplied path can be walked out of the folder.
    if (preg_match('#^(assets/menu|uploads/menu)/([A-Za-z0-9._-]+\.(?:jpg|jpeg|png|webp))$#i', $path, $m)) {
        $thumb = $m[1] . '/' . $sub . $m[2];
        if (is_file(PUBLIC_ROOT . '/' . $thumb)) {
            return $thumb;
        }
    }

    return $path;
}

/**
 * Create the two thumbnail sizes for an uploaded photo.
 *
 * Called after a canteen uploads a dish photo. Anything that fails is
 * ignored on purpose: a missing thumbnail only costs bandwidth, because
 * menu_photo_url() falls back to the full image.
 */
function menu_photo_make_thumbs(string $publicRelativePath): void
{
    if (!function_exists('imagecreatetruecolor')) {
        return;                                    // no GD, no thumbnails
    }

    $full = PUBLIC_ROOT . '/' . $publicRelativePath;
    if (!is_file($full)) {
        return;
    }

    preg_match('#^(.+)/([^/]+)$#', $publicRelativePath, $m);
    if (!$m) {
        return;
    }
    [, $dir, $file] = $m;

    $source = @imagecreatefromjpeg($full);
    if ($source === false) {
        return;
    }

    $srcW = imagesx($source);
    $srcH = imagesy($source);

    foreach ([['thumbs/', 512], ['thumbs/tiny/', 160]] as [$sub, $width]) {
        $targetDir = PUBLIC_ROOT . '/' . $dir . '/' . $sub;
        if (!is_dir($targetDir) && !@mkdir($targetDir, 0755, true)) {
            continue;
        }

        $newW = min($width, $srcW);
        $newH = (int) round($srcH * ($newW / $srcW));

        $canvas = imagecreatetruecolor($newW, $newH);
        imagecopyresampled($canvas, $source, 0, 0, 0, 0, $newW, $newH, $srcW, $srcH);
        @imagejpeg($canvas, $targetDir . '/' . $file, 80);
        imagedestroy($canvas);
    }

    imagedestroy($source);
}

/** "2026-09-29 12:04:00" -> "Sep 29, 2026 · 12:04 PM" */
function nice_date(?string $sqlDate, bool $withTime = true): string
{
    if (!$sqlDate) {
        return '—';
    }
    $ts = strtotime($sqlDate);

    return date($withTime ? 'M j, Y · g:i A' : 'M j, Y', $ts);
}

/** How long ago, e.g. "20 minutes ago". */
function time_ago(?string $sqlDate): string
{
    if (!$sqlDate) {
        return '—';
    }
    $diff = time() - strtotime($sqlDate);
    if ($diff < 60)    return 'just now';
    if ($diff < 3600)  return floor($diff / 60) . ' min ago';
    if ($diff < 86400) return floor($diff / 3600) . ' hr ago';

    return floor($diff / 86400) . ' day(s) ago';
}

/** Send a redirect and stop. Always exit afterwards. */
function redirect(string $path): never
{
    header('Location: ' . url($path));
    exit;
}

/** All the order statuses the app understands, in workflow order. */
function order_statuses(): array
{
    return ['pending', 'preparing', 'ready', 'completed', 'cancelled'];
}

/** "preparing" -> "Preparing" */
function status_label(string $status): string
{
    return ucwords(str_replace('_', ' ', $status));
}

/** A coloured pill for an order status, with its icon. */
function status_badge(string $status): string
{
    $class = in_array($status, order_statuses(), true) ? $status : 'pending';

    return '<span class="badge badge-' . e($class) . '">'
         . icon(status_icon_name($status), 14, 'ico-badge')
         . '<span>' . e(status_label($status)) . '</span>'
         . '</span>';
}

/** The icon name for an order status. */
function status_icon_name(string $status): string
{
    return [
        'pending'   => 'clock',
        'preparing' => 'kitchen',
        'ready'     => 'bell',
        'completed' => 'check',
        'cancelled' => 'ban',
    ][$status] ?? 'clock';
}

/** Icon for a status, used on the tracking timeline. */
function status_icon(string $status): string
{
    return icon(status_icon_name($status), 20, 'ico-status');
}

