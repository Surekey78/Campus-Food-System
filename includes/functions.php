/** The logged-in user row, or null for a guest. */
function current_user(): ?array
{
    static $user = null;
    static $loaded = false;

    if ($loaded) {
        return $user;
    }
    $loaded = true;

    $id = $_SESSION['user_id'] ?? null;

    if ($id) {
        $user = db_one(
            'SELECT id, name, email, student_id, phone, role, wallet FROM users WHERE id = ?',
            [(int) $id]
        );

        if ($user === null) {          // account was deleted mid-session
            unset($_SESSION['user_id']);
        }
    }

    return $user;
}

function is_logged_in(): bool
{
    return current_user() !== null;
}

function is_admin(): bool
{
    return (current_user()['role'] ?? '') === 'admin';
}

/** Bounce guests to the login page (remembering where they wanted to go). */
function require_login(): array
{
    if (!is_logged_in()) {
        $_SESSION['after_login'] = $_SERVER['REQUEST_URI'] ?? url('/');
        flash('Please sign in to continue.', 'warn');
        redirect('/login.php');
    }

    return current_user();
}

/** Bounce non-admins away from the canteen back office. */
function require_admin(): array
{
    $user = require_login();

    if ($user['role'] !== 'admin') {
        flash('That area is for canteen staff only.', 'error');
        redirect('/index.php');
    }

    return $user;
}

// =====================================================================
//  6. Cart  —  $_SESSION['cart'] = [ menu_item_id => quantity ]
// =====================================================================

function cart(): array
{
    return $_SESSION['cart'] ?? [];
}

/** Total number of individual items in the cart (for the header badge). */
function cart_count(): int
{
    return array_sum(cart());
}

/** Load the full menu rows for everything currently in the cart. */
function cart_lines(): array
{
    $cart = cart();

    if ($cart === []) {
        return [];
    }

    $ids  = array_map('intval', array_keys($cart));
    $hold = implode(',', array_fill(0, count($ids), '?'));

    $rows = db_all(
        "SELECT id, name, icon, price, stock, is_available, image_path
           FROM menu_items
          WHERE id IN ($hold)
          ORDER BY name",
        $ids
    );

    $lines = [];
    foreach ($rows as $row) {
        $qty = (int) $cart[$row['id']];
        if ($qty < 1) {
            continue;
        }
        $row['quantity']   = $qty;
        $row['line_total'] = $qty * (float) $row['price'];
        $lines[]           = $row;
    }

    return $lines;
}

/** Sum of every line total. */
function cart_subtotal(): float
{
    $total = 0.0;
    foreach (cart_lines() as $line) {
        $total += $line['line_total'];
    }

    return round($total, 2);
}

/** Set an item to an exact quantity (0 removes it). */
function cart_set(int $itemId, int $qty): void
{
    if ($qty <= 0) {
        unset($_SESSION['cart'][$itemId]);

        return;
    }

    $_SESSION['cart'][$itemId] = $qty;
}

/** Add to the cart, never going above available stock. */
function cart_add(int $itemId, int $qty = 1): bool
{
    $item = db_one('SELECT id, stock, is_available FROM menu_items WHERE id = ?', [$itemId]);

    if (!$item || (int) $item['is_available'] !== 1) {
        flash('That item is not available right now.', 'error');

        return false;
    }

    $current = (int) (cart()[$itemId] ?? 0);
    $wanted  = $current + max(1, $qty);
    $stock   = (int) $item['stock'];

    if ($wanted > $stock) {
        $_SESSION['cart'][$itemId] = $stock;
        flash($stock > 0
            ? "Only $stock left — cart adjusted."
            : 'That item just sold out.', $stock > 0 ? 'warn' : 'error');

        return $stock > 0;
    }

    $_SESSION['cart'][$itemId] = $wanted;

    return true;
}

function cart_remove(int $itemId): void
{
    unset($_SESSION['cart'][$itemId]);
}

function cart_clear(): void
{
    unset($_SESSION['cart']);
}
